def _shuffled(choices, answer, seed):
    """Deterministically reorder choices per-question so the correct answer
    isn't disproportionately at index 0 (a real bias: most of these were
    authored with the correct choice written first)."""
    rng = random.Random(seed)
    order = list(range(len(choices)))
    rng.shuffle(order)
    new_choices = [choices[i] for i in order]
    new_answer = order.index(answer)
    return new_choices, new_answer


def _slug(topic):
    text = topic.lower().replace("#", "sharp").replace("+", "p")
    out = []
    for ch in text:
        out.append(ch if ch.isalnum() else "_")
    slug = "".join(out)
    while "__" in slug:
        slug = slug.replace("__", "_")
    return slug.strip("_")


