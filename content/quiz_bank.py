        qid = f"{prefix}_{i:02d}"
        shuffled_choices, shuffled_answer = _shuffled(choices, answer, seed=qid)
        QUESTIONS.append({
            "id": qid,
            "topic": topic,
            "question": question,
            "choices": shuffled_choices,
            "answer": shuffled_answer,
            "explanation": explanation,
        })

